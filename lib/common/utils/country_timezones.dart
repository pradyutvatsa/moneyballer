class CountryTimezoneHelper {
  static bool _initialized = false;

  static void ensureInitialized() {
    if (!_initialized) {
      tz_data.initializeTimeZones();
      _initialized = true;
    }
  }

  /// Resolves a country name (e.g., "Australia") to its list of formatted time zones.
  static List<String> getTimezonesForCountryName(String countryName) {
    ensureInitialized();

    final Country? parsed = CountryParser.tryParseCountryName(countryName);
    final String code = parsed?.countryCode.toUpperCase() ?? '';

    final List<String> zones =
        _countryCodeToZones[code] ?? _allAvailableZones();
    return zones.map(_formatZoneWithOffset).toList();
  }

  static String _formatZoneWithOffset(String ianaName) {
    try {
      final location = tz.getLocation(ianaName);
      final now = tz.TZDateTime.now(location);
      final offset = now.timeZoneOffset;
      final sign = offset.isNegative ? '-' : '+';
      final hours = offset.inHours.abs().toString().padLeft(2, '0');
      final minutes = (offset.inMinutes.abs() % 60).toString().padLeft(2, '0');
      return '$ianaName (UTC$sign$hours:$minutes)';
    } catch (_) {
      return ianaName;
    }
  }

  static List<String> _allAvailableZones() {
    final keys = tz.timeZoneDatabase.locations.keys.toList()..sort();
    return keys;
  }

